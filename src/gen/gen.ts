import { Data } from "effect";
import { mkdir, readFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { writeFileAtomic } from "../fs/atomic.ts";
import { detectFramework, readPackageJson } from "./detect.ts";
import { loadRequests } from "./load.ts";
import type { LoadedRequest } from "./load.ts";
import { GENERATED_BY, renderTest } from "./render.ts";
import { TEST_TARGETS } from "./targets.ts";
import type { TestTarget } from "./targets.ts";

export class UnsupportedTargetError extends Data.TaggedError("UnsupportedTargetError")<
  { message: string }
> {}

export class GenCollisionError extends Data.TaggedError("GenCollisionError")<
  { message: string }
> {}

export interface GenOptions {
  /** Workspace root holding package.json, requests/, and tests/. Defaults to cwd. */
  root?: string;
  /** Explicit target framework; overrides package.json detection. */
  framework?: string | null;
}

export interface GenResult {
  target: TestTarget;
  /** Paths of generated test files; empty when the requests folder is empty. */
  files: string[];
}

const REQUESTS_DIR = "requests";
const TESTS_DIR = "tests";

/**
 * Generate one framework-native test file per saved request. Everything
 * that can fail — target selection, module loading, destination checks —
 * happens before the first write; each file is then replaced atomically via
 * a temp file and rename, so no destination ever holds a partial file.
 */
export async function generateTests(opts: GenOptions = {}): Promise<GenResult> {
  const root = opts.root ?? process.cwd();
  const target = await resolveTarget(root, opts.framework ?? null);
  const outDir = join(root, TESTS_DIR);
  const requests = await loadRequests(join(root, REQUESTS_DIR));
  if (requests.length === 0) return { target, files: [] };

  const plan = planGeneration(requests, outDir, target);
  await Promise.all(plan.map(p => assertReplaceable(p.dest)));
  await mkdir(outDir, { recursive: true });
  await Promise.all(plan.map(p => writeFileAtomic(p.dest, p.content)));
  return { target, files: plan.map(p => relative(root, p.dest)) };
}

async function resolveTarget(root: string, framework: string | null): Promise<TestTarget> {
  if (framework === null) return detectFramework(await readPackageJson(root));
  return declaredTarget(framework);
}

/** The flag must name a target the targets module declares; Jest never is. */
function declaredTarget(flag: string): TestTarget {
  if (flag.toLowerCase() === "jest") {
    throw new UnsupportedTargetError({
      message:
        "Jest is deliberately unsupported (a postui non-goal) — " +
        "targets are vitest, bun:test, and node:test",
    });
  }
  const target = (TEST_TARGETS as readonly string[]).find(t => t === flag);
  if (target === undefined) {
    throw new UnsupportedTargetError({
      message: `unknown test target "${flag}" — targets are vitest, bun:test, and node:test`,
    });
  }
  return target as TestTarget;
}

interface PlannedFile {
  dest: string;
  content: string;
}

function planGeneration(requests: LoadedRequest[], outDir: string, target: TestTarget): PlannedFile[] {
  return requests.map(request => {
    const dest = join(outDir, `${request.name}.test.ts`);
    const content = renderTest(target, {
      name: request.name,
      importPath: relativeImport(outDir, request.path),
    });
    return { dest, content };
  });
}

/** "../requests/<name>.ts" from the tests folder, always a relative specifier. */
function relativeImport(outDir: string, requestPath: string): string {
  const rel = relative(outDir, requestPath);
  const posix = rel.split("\\").join("/");
  return posix.startsWith(".") ? posix : `./${posix}`;
}

/** A destination may be created or replaced only if postui generated it (or it is new). */
async function assertReplaceable(dest: string): Promise<void> {
  let existing: string;
  try {
    existing = await readFile(dest, "utf8");
  } catch {
    return; // no destination yet — nothing to clobber
  }
  if (!existing.startsWith(GENERATED_BY)) {
    throw new GenCollisionError({
      message: `${dest} exists and was not generated by postui — rename or remove it first`,
    });
  }
}
